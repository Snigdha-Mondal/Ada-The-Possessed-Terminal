"""Rich TrueColor gothic tomb terminal renderer for Ada: The Possessed Terminal."""

import sys
from enum import Enum
from typing import Optional
from rich.console import Console
from rich.panel import Panel
from rich.text import Text
from rich.table import Table
from rich.columns import Columns

from .ascii_art import LADY_LOVELACE_PORTRAIT

# Ensure UTF-8 output encoding across all platforms
if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass


class OccultTier(Enum):
    """Occult failure classification tiers."""
    TIER_1 = (1, "Minor Poltergeist", "#f59e0b", "[*]")     # Amber
    TIER_2 = (2, "Malicious Daemon", "#c084fc", "[+]")       # Violet
    TIER_3 = (3, "Demonic Possession", "#dc2626", "[!]")     # Blood-crimson
    TIER_4 = (4, "Abyssal Cataclysm", "#f43f5e", "[#]")     # Abyssal rose/crimson

    def __init__(self, level: int, title: str, color_hex: str, symbol: str):
        self.level = level
        self.tier_title = title
        self.color_hex = color_hex
        self.symbol = symbol


# Shared Console instance supporting TrueColor with Windows safety
console = Console(highlight=False, legacy_windows=False, safe_box=True)


def render_autopsy_panel(
    diagnosis: str,
    fix: str,
    tier: OccultTier = OccultTier.TIER_3,
    command: Optional[str] = None,
    exit_code: int = 1,
    is_fallback: bool = False
) -> None:
    """
    Renders the blood-crimson / gothic crypt terminal panel displaying
    Lady Lovelace's diagnosis and the clean Incantation of Exorcism fix command.

    Args:
        diagnosis: 2-3 sentences of Victorian Poetical Science prose.
        fix: Precise executable terminal fix command.
        tier: Occult severity classification tier.
        command: Original failed command string.
        exit_code: Non-zero exit code intercepted.
        is_fallback: Whether the diagnosis was generated by offline oracle fallback.
    """
    border_color = tier.color_hex

    # Build Header Title
    header_text = Text()
    header_text.append(f"{tier.symbol} ", style=f"bold {border_color}")
    header_text.append("ADA'S AUTOPSY ", style=f"bold underline {border_color}")
    header_text.append("— ", style="dim white")
    header_text.append(f"{tier.tier_title.upper()} ", style=f"bold {tier.color_hex}")
    header_text.append(f"[Exit Status: {exit_code}]", style="dim red")

    # Left Column: Lady Lovelace Portrait
    portrait_lines = "\n".join(LADY_LOVELACE_PORTRAIT)
    portrait_text = Text(portrait_lines, style=f"bold {border_color}")
    portrait_panel = Panel(
        portrait_text,
        title="[bold dim white]Ada Lovelace[/]",
        border_style="dim " + border_color,
        padding=(0, 1)
    )

    # Right Column: Autopsy & Incantation Content
    content_table = Table.grid(padding=(0, 1))
    content_table.add_column("Key", style="bold white", width=14)
    content_table.add_column("Value", style="white")

    # Target Command row
    if command:
        cmd_text = Text(command, style="bold yellow")
        content_table.add_row("[dim]Afflicted Cmd:[/]", cmd_text)
        content_table.add_row("", "")

    # Diagnosis row (Ectoplasm Green #a7f3d0)
    diag_text = Text()
    diag_text.append(diagnosis.strip(), style="italic #a7f3d0")
    content_table.add_row("[bold #a7f3d0]Diagnosis:[/]", diag_text)
    content_table.add_row("", "")

    # Incantation of Exorcism row (Phosphor Cyan #00f5d4)
    fix_panel = Panel(
        Text(f" {fix.strip()} ", style="bold #00f5d4"),
        title="[bold #00f5d4]-- INCANTATION OF EXORCISM (THE FIX) --[/]",
        border_style="bold #00f5d4",
        padding=(0, 1)
    )
    content_table.add_row("[bold #00f5d4]Exorcism:[/]", fix_panel)

    # Subtitle / Footer info
    engine_label = "Built-in Deterministic Oracle (Offline)" if is_fallback else "Google Gemma 2 (2B) Local Inference"
    footer_text = f"* 1843 Poetical Science | {engine_label} | Zero Cloud Telemetry *"

    # Assemble Main Tomb Panel
    columns = Columns([portrait_panel, content_table], expand=True)
    tomb_panel = Panel(
        columns,
        title=header_text,
        subtitle=f"[dim white]{footer_text}[/]",
        border_style=f"bold {border_color}",
        padding=(1, 2)
    )

    console.print()
    console.print(tomb_panel)
    console.print()
